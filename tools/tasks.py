#!/usr/bin/env python3
"""Index generator and consistency check for work items in tasks/.

Usage:
    tools/tasks.py index          regenerate tasks/INDEX.md
    tools/tasks.py check [--ci]   validate items and that INDEX.md is current

Duplicate IDs are a warning locally and an error with --ci (or when the CI
environment variable is set). See spec/SPEC-work-tracking.md.
"""
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "tasks"
FINISHED = TASKS / "finished"
INDEX = TASKS / "INDEX.md"

TYPES = {"task", "bug", "decision", "spike"}
STATUSES = {"open", "in-progress", "blocked", "finished"}
PRIORITIES = {"high", "normal", "low"}
REQUIRED = ["id", "type", "status", "priority", "area", "created"]
ID_RE = re.compile(r"^AVARC-([1-9][0-9]*)$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


class Item:
    def __init__(self, path):
        self.path = path
        self.rel = path.relative_to(ROOT).as_posix()
        self.fields = {}
        self.title = path.stem
        self.problems = []
        self._parse()

    def _parse(self):
        lines = self.path.read_text().splitlines()
        if not lines or lines[0] != "---":
            self.problems.append("missing front matter")
            return
        try:
            end = lines.index("---", 1)
        except ValueError:
            self.problems.append("unterminated front matter")
            return
        for line in lines[1:end]:
            if not line.strip():
                continue
            key, sep, value = line.partition(":")
            if not sep:
                self.problems.append(f"bad front matter line: {line!r}")
                continue
            self.fields[key.strip()] = value.strip()
        for line in lines[end + 1:]:
            m = re.match(r"# (?:TASK: )?(.+)", line)
            if m:
                self.title = m.group(1).strip()
                break

    @property
    def id(self):
        return self.fields.get("id", "")

    @property
    def number(self):
        m = ID_RE.match(self.id)
        return int(m.group(1)) if m else 10**9

    @property
    def depends(self):
        raw = self.fields.get("depends-on", "").strip()
        if not raw:
            return []
        if raw.startswith("[") and raw.endswith("]"):
            raw = raw[1:-1]
        return [d.strip() for d in raw.split(",") if d.strip()]


def load():
    paths = sorted(TASKS.glob("TASK-*.md")) + sorted(FINISHED.glob("TASK-*.md"))
    return sorted((Item(p) for p in paths), key=lambda i: (i.number, i.rel))


def render_index(items):
    out = [
        "# Work items",
        "",
        "Generated by `tools/tasks.py index` from the front matter of the task",
        "files. Do not edit by hand. See",
        "[SPEC-work-tracking.md](../spec/SPEC-work-tracking.md).",
        "",
        "| ID | Title | Type | Status | Priority | Area | Depends on |",
        "|----|-------|------|--------|----------|------|------------|",
    ]
    for i in items:
        link = i.rel[len("tasks/"):]
        f = i.fields
        out.append(
            f"| {i.id} | [{i.title}]({link}) | {f.get('type', '')} "
            f"| {f.get('status', '')} | {f.get('priority', '')} "
            f"| {f.get('area', '')} | {', '.join(i.depends)} |"
        )
    return "\n".join(out) + "\n"


def check(items, ci):
    errors, warnings = [], []
    ids = {}
    for i in items:
        for p in i.problems:
            errors.append(f"{i.rel}: {p}")
        if i.problems:
            continue
        f = i.fields
        for key in REQUIRED:
            if not f.get(key):
                errors.append(f"{i.rel}: missing field {key!r}")
        if f.get("id") and not ID_RE.match(f["id"]):
            errors.append(f"{i.rel}: invalid id {f['id']!r}")
        for key, allowed in (("type", TYPES), ("status", STATUSES),
                             ("priority", PRIORITIES)):
            if f.get(key) and f[key] not in allowed:
                errors.append(f"{i.rel}: invalid {key} {f[key]!r}")
        if f.get("created") and not DATE_RE.match(f["created"]):
            errors.append(f"{i.rel}: invalid created date {f['created']!r}")
        in_finished = i.path.parent == FINISHED
        if f.get("status") and (f["status"] == "finished") != in_finished:
            where = "tasks/finished/" if f["status"] == "finished" else "tasks/"
            errors.append(f"{i.rel}: status {f['status']!r} belongs in {where}")
        if i.id:
            ids.setdefault(i.id, []).append(i.rel)
    for id_, files in ids.items():
        if len(files) > 1:
            (errors if ci else warnings).append(
                f"duplicate id {id_}: {', '.join(files)}")
    for i in items:
        for d in i.depends:
            if d not in ids:
                errors.append(f"{i.rel}: depends-on {d!r} does not resolve")
    if not errors and not any(i.problems for i in items):
        if not INDEX.exists() or INDEX.read_text() != render_index(items):
            errors.append("tasks/INDEX.md is out of date; run tools/tasks.py index")
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    return 1 if errors else 0


def main(argv):
    ci = "--ci" in argv or bool(os.environ.get("CI"))
    args = [a for a in argv if a != "--ci"]
    if len(args) != 1 or args[0] not in ("index", "check"):
        print(__doc__, file=sys.stderr)
        return 2
    items = load()
    if args[0] == "index":
        INDEX.write_text(render_index(items))
        print(f"wrote {INDEX.relative_to(ROOT)} ({len(items)} items)")
        return 0
    return check(items, ci)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
